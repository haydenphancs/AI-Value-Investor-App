    /// `GET /api/v1/updates/sentiment-trend` — `days` ET calendar days ending TODAY in New York
    /// (the app's axis ends there), today's bar partial, and a `tracking_since` long before every
    /// window, so the chart reads as fully covered and the legend shows no coverage note (the app
    /// shows one only for an incomplete chart). The counts look like real news (owner,
