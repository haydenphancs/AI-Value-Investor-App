    /// negative streaks, uneven daily volume, quieter weekends and the odd news-heavy day — all
    /// from a deterministic hash of the DATE, so a re-capture draws the same bars.
    static func sentimentTrendJSON(scope: String, days requested: Int, now: Date = Date()) -> Data {
        let count: Int = max(1, min(requested, 90))
        let calendar: Calendar = easternCalendar
        let today: Date = calendar.startOfDay(for: now)
        var series: [[String: Any]] = []
        var mood: Double = 0.0
        for index in 0..<count {
            let offset: Int = count - 1 - index
            guard let date = calendar.date(byAdding: .day, value: -offset, to: today) else { continue }
            let day: Int = ordinalDay(date)
            let step: Double = (2.0 * noise(day: day, salt: 2) - 1.0) * 1.6
            mood = max(-1.0, min(1.0, 0.35 * mood + 0.65 * step))
            var positiveShare: Double = 0.40 + 0.42 * mood + 0.30 * (noise(day: day, salt: 3) - 0.5)
            var negativeShare: Double = 0.32 - 0.38 * mood + 0.30 * (noise(day: day, salt: 4) - 0.5)
            positiveShare = min(max(positiveShare, 0.06), 0.86)
            negativeShare = min(max(negativeShare, 0.05), 0.82)
            let shareSum: Double = positiveShare + negativeShare
            if shareSum > 0.95 {
                positiveShare *= 0.95 / shareSum
                negativeShare *= 0.95 / shareSum
            }
            var volume: Double = 8.0 + 30.0 * noise(day: day, salt: 1)
            let weekday: Int = calendar.component(.weekday, from: date)
            if weekday == 1 || weekday == 7 { volume *= 0.5 }
            if noise(day: day, salt: 5) > 0.84 { volume *= 2.0 }
            if offset == 0 { volume *= 0.45 }
            let total: Int = max(2, Int(volume.rounded()))
            let positive: Int = Int((Double(total) * positiveShare).rounded())
            let negative: Int = Int((Double(total) * negativeShare).rounded())
            let neutral: Int = max(0, total - positive - negative)
            let sum: Int = positive + negative + neutral
            let net: Int = sum > 0 ? Int((Double(positive - negative) * 100.0 / Double(sum)).rounded()) : 0
            var row: [String: Any] = [:]
            row["date"] = easternDayKey(date)
            row["bullish"] = positive
            row["bearish"] = negative
            row["neutral"] = neutral
            row["total"] = sum
            row["net_score"] = net
            row["is_partial"] = offset == 0
            series.append(row)
        }
        let since: Date = calendar.date(byAdding: .day, value: -150, to: today) ?? today
        var body: [String: Any] = [:]
        body["scope"] = scope
        body["days"] = count
        body["series"] = series
        body["tracking_since"] = easternDayKey(since)
        body["history_status"] = "ready"
        return json(body)
    }

    /// Deterministic noise in [0, 1) for one calendar day and stream: splitmix64's finalizer
    /// over the day number, so the same date always draws the same value.
    static func noise(day: Int, salt: Int) -> Double {
        var x: UInt64 = UInt64(truncatingIfNeeded: day) &* 0x9E37_79B9_7F4A_7C15
        x = x &+ UInt64(truncatingIfNeeded: salt) &* 0xBF58_476D_1CE4_E5B9
        x = x &+ 0x94D0_49BB_1331_11EB
        x ^= x >> 30
        x = x &* 0xBF58_476D_1CE4_E5B9
        x ^= x >> 27
        x = x &* 0x94D0_49BB_1331_11EB
        x ^= x >> 31
        return Double(x >> 11) / 9_007_199_254_740_992.0
    }

    /// The proleptic-Gregorian day number of an ET calendar day (Python's `date.toordinal()`):
    /// a stable integer per DATE for `noise`.
    static func ordinalDay(_ date: Date) -> Int {
        let parts: DateComponents = easternCalendar.dateComponents([.year, .month, .day], from: date)
        var utc = Calendar(identifier: .gregorian)
        utc.timeZone = TimeZone(identifier: "UTC") ?? .current
        let midnight: Date = utc.date(from: parts) ?? date
        return Int((midnight.timeIntervalSince1970 / 86_400.0).rounded(.down)) + 719_163
    }

    static let easternCalendar: Calendar = {
        var calendar = Calendar(identifier: .gregorian)
        calendar.timeZone = TimeZone(identifier: "America/New_York") ?? .current
        return calendar
    }()

    static func easternDayKey(_ date: Date) -> String {
        let formatter = DateFormatter()
        formatter.calendar = easternCalendar
        formatter.locale = Locale(identifier: "en_US_POSIX")
        formatter.timeZone = easternCalendar.timeZone
        formatter.dateFormat = "yyyy-MM-dd"
        return formatter.string(from: date)
    }

    static func isoUTC(_ date: Date) -> String {
        let formatter = ISO8601DateFormatter()
        formatter.formatOptions = [.withInternetDateTime]
        return formatter.string(from: date)
    }

    private static func json(_ object: Any) -> Data {
        do {
            return try JSONSerialization.data(withJSONObject: object)
        } catch {
            print("📸 [StoreScreenshotMode] fixture encode failed: \(type(of: error)): \(error)")
            return Data("{}".utf8)
        }
    }
