// MARK: - Network fixtures

/// Answers the Tracking and Updates reads with fixtures and swallows the writes they can
/// trigger. Registered on `URLSession.shared` (which `APIClient` uses) only while
/// `StoreScreenshotMode.isOn`; every other request passes through untouched.
nonisolated final class StoreShotURLProtocol: URLProtocol {
    private enum Route {
        case trackingFeed, portfolios, portfolioInsights, updatesTabs, portfolioWrite, swallowedWrite
        case updatesFeed(scope: String)
        case sentimentTrend(scope: String, days: Int)
    }

    private static func query(_ name: String, in url: URL) -> String? {
        let items: [URLQueryItem] = URLComponents(url: url, resolvingAgainstBaseURL: false)?.queryItems ?? []
        return items.first(where: { $0.name == name })?.value
    }

    private static func route(for request: URLRequest) -> Route? {
        guard StoreScreenshotMode.isOn, let url = request.url else { return nil }
        let path = url.path
        let method = (request.httpMethod ?? "GET").uppercased()
        if method == "GET" {
            if path.hasSuffix("/api/v1/tracking/assets") { return .trackingFeed }
            if path.hasSuffix("/api/v1/portfolios") { return .portfolios }
            if path.contains("/api/v1/portfolios/"), path.hasSuffix("/insights") { return .portfolioInsights }
            if path.hasSuffix("/api/v1/updates/tabs") { return .updatesTabs }
            if path.hasSuffix("/api/v1/updates/feed") {
                return .updatesFeed(scope: query("scope", in: url) ?? StoreShotFixtures.marketScope)
            }
            if path.hasSuffix("/api/v1/updates/sentiment-trend") {
                let scope: String = query("scope", in: url) ?? StoreShotFixtures.marketScope
                let days: Int = Int(query("days", in: url) ?? "") ?? 90
                return .sentimentTrend(scope: scope, days: days)
            }
            return nil
        }
        if path.contains("/api/v1/portfolios") { return .portfolioWrite }
        if path.contains("/api/v1/tracking/assets/holdings") || path.contains("/api/v1/watchlist") {
            return .swallowedWrite
        }
        return nil
    }

    override class func canInit(with request: URLRequest) -> Bool {
        route(for: request) != nil
    }

    override class func canonicalRequest(for request: URLRequest) -> URLRequest {
        request
    }

    override func startLoading() {
        guard let url = request.url, let route = Self.route(for: request) else {
            client?.urlProtocol(self, didFailWithError: URLError(.unsupportedURL))
            return
        }
        let body: Data
        switch route {
        case .trackingFeed: body = StoreShotFixtures.trackingFeedJSON()
        case .portfolios: body = StoreShotFixtures.portfoliosJSON()
        case .portfolioInsights: body = Data("null".utf8)
        case .updatesTabs: body = StoreShotFixtures.updatesTabsJSON()
        case .updatesFeed(let scope): body = StoreShotFixtures.updatesFeedJSON(scope: scope)
        case .sentimentTrend(let scope, let days):
            body = StoreShotFixtures.sentimentTrendJSON(scope: scope, days: days)
        case .portfolioWrite: body = StoreShotFixtures.portfolioJSON()
        case .swallowedWrite: body = Data("{}".utf8)
        }
        guard let response = HTTPURLResponse(
            url: url, statusCode: 200, httpVersion: "HTTP/1.1",
            headerFields: ["Content-Type": "application/json"]
        ) else {
            client?.urlProtocol(self, didFailWithError: URLError(.badServerResponse))
            return
        }
        client?.urlProtocol(self, didReceive: response, cacheStoragePolicy: .notAllowed)
        client?.urlProtocol(self, didLoad: body)
        client?.urlProtocolDidFinishLoading(self)
    }

    override func stopLoading() {}
}
