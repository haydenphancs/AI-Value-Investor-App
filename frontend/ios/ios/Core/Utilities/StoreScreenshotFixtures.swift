    static func series(seed: Int, count: Int, from start: Double, to end: Double) -> [Double] {
        var points: [Double] = []
        points.reserveCapacity(count)
        let span: Double = max(abs(end - start), start * 0.004)
        let phase: Double = Double(seed) * 1.7
        let last: Double = Double(max(count - 1, 1))
